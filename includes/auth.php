<?php
/**
 * includes/auth.php — کتابخانهٔ احراز هویت و بازیابی رمز عبور
 * ------------------------------------------------------------------
 * این فایل توابع کمکی مرتبط با ورود، محدودسازی نرخ تلاش و بازیابی
 * رمز عبور را در یک نقطهٔ مرجع نگه می‌دارد.
 *
 * بازیابی رمز عبور به‌صورت «بدون SMTP» پیاده‌سازی شده است:
 * ایمیل ثبت‌شدهٔ حساب به‌عنوان راز هویتی با ورودی کاربر مقایسه می‌شود
 * و در صورت تطبیق، امکان ثبت رمز جدید فراهم می‌شود.
 */

require_once __DIR__ . '/../config.php';

/**
 * محافظ Rate Limiting برای ورود (کاربر و مدیر).
 *
 * این تابع فقط یک wrapper سنددار روی rate_limit_check() در functions.php است.
 * تعریف اصلی در functions.php قرار دارد تا از هر صفحهٔ عمومی (login.php و…) قابل دسترسی باشد.
 * این نسخه فقط در صورتی تعریف می‌شود که نسخهٔ functions.php از قبل بارگذاری نشده باشد.
 */
if (!function_exists('login_rate_limit')) {
    function login_rate_limit($username)
    {
        return rate_limit_check($username, 5, 900); // ۵ تلاش در ۱۵ دقیقه
    }
}
